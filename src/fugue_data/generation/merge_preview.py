"""Fold a reviewed preview batch into the real preference dataset (Spec §18).

A preview batch is generated by the same solver, validator and ruleset as the
main run, so its candidates are ordinary members of the corpus -- the only thing
that made them "preview" was where they were written. What cannot be regenerated
is the human judgment attached to them, so the labels are the reason to merge.

Two properties make this safe:

  `pair_id` is derived from the two candidates' event hashes, so a label can only
  ever bind to the exact pair of fragments it was made against. A stale label
  fails to match rather than attaching to different music.

  Labels are carried across as *human* review -- `reviewer` and `reviewed_at_utc`
  come from the reviewer who made them -- because a person really did listen and
  judge. Nothing here invents a label for an unreviewed pair.
"""

from __future__ import annotations

import json
from pathlib import Path


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _read(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


def _write(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text("".join(
        json.dumps(r, sort_keys=True, separators=(",", ":")) + "\n" for r in rows))
    tmp.replace(path)


def merge(root: Path | None = None, *, preview_root: Path,
          labelled_only: bool = False) -> dict:
    root = root or _repo_root()
    live = root / "data" / "generated" / "preference_candidates"
    pv = Path(preview_root) / "data" / "generated" / "preference_candidates"

    live_cands = _read(live / "candidates.jsonl")
    live_pairs = _read(live / "pairs.jsonl")
    pv_cands = _read(pv / "candidates.jsonl")
    pv_pairs = _read(pv / "pairs.jsonl")
    if not pv_pairs:
        raise RuntimeError(f"no preview pairs at {pv}")

    reviewed = [p for p in pv_pairs
                if p.get("review_status") == "reviewed" and p.get("label")]
    keep_pairs = reviewed if labelled_only else pv_pairs
    needed = {p["candidate_a_id"] for p in keep_pairs} | \
             {p["candidate_b_id"] for p in keep_pairs}

    by_id = {c["sample_id"]: c for c in live_cands}
    added_c = 0
    for c in pv_cands:
        if c["sample_id"] in needed and c["sample_id"] not in by_id:
            merged = dict(c)
            # These are ordinary candidates; record where they came from rather
            # than leaving a `preview` source type that downstream code would
            # have to special-case.
            merged["source_type"] = "synthetic_preference_candidate"
            merged["provenance"] = "preview_batch"
            by_id[c["sample_id"]] = merged
            added_c += 1

    existing = {p["pair_id"]: p for p in live_pairs}
    added_p = carried = conflicts = 0
    for p in keep_pairs:
        if p["candidate_a_id"] not in by_id or p["candidate_b_id"] not in by_id:
            continue
        prior = existing.get(p["pair_id"])
        if prior is None:
            existing[p["pair_id"]] = dict(p)
            added_p += 1
            if p.get("label"):
                carried += 1
        else:
            # Same pair reached from both batches: keep the human label, and
            # never overwrite one label with a different one.
            if p.get("label") and prior.get("label") and p["label"] != prior["label"]:
                conflicts += 1
                continue
            if p.get("label") and not prior.get("label"):
                for f in ("label", "review_status", "reviewer", "review_comment",
                          "reviewed_at_utc"):
                    prior[f] = p.get(f, prior.get(f))
                carried += 1

    out_c = sorted(by_id.values(), key=lambda c: c["sample_id"])
    out_p = sorted(existing.values(), key=lambda p: p["pair_id"])
    _write(live / "candidates.jsonl", out_c)
    _write(live / "pairs.jsonl", out_p)

    labelled = sum(1 for p in out_p
                   if p.get("review_status") == "reviewed" and p.get("label"))
    dist: dict[str, int] = {}
    for p in out_p:
        if p.get("label"):
            dist[p["label"]] = dist.get(p["label"], 0) + 1
    summary = {
        "stage": "merge_preview",
        "preview_root": str(preview_root),
        "preview_pairs_seen": len(pv_pairs),
        "preview_pairs_reviewed": len(reviewed),
        "candidates_added": added_c,
        "pairs_added": added_p,
        "human_labels_carried": carried,
        "label_conflicts_skipped": conflicts,
        "total_pairs": len(out_p),
        "total_human_labelled": labelled,
        "label_distribution": dict(sorted(dist.items())),
        "note": ("Preview candidates were produced by the same solver, validator "
                 "and ruleset as the main run, so they are ordinary corpus "
                 "members; `provenance: preview_batch` records where they came "
                 "from. Labels are carried as human review because a person made "
                 "them."),
    }
    (root / "manifests" / "preview_merge_summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n")
    return summary
